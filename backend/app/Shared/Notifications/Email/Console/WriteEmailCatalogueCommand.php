<?php

namespace App\Shared\Notifications\Email\Console;

use App\Shared\Notifications\Email\EmailCatalogue;
use App\Shared\Notifications\Email\EmailCategory;
use Illuminate\Console\Command;

/**
 * Writes docs/project/email-catalogue.md from the code registry, so the
 * document never drifts from what the platform sends.
 */
class WriteEmailCatalogueCommand extends Command
{
    protected $signature = 'nawy:emails:catalogue {--path= : Output path (default docs/project/email-catalogue.md at the repository root)}';

    protected $description = 'Generate the email catalogue document from the registry';

    public function handle(): int
    {
        $path = $this->option('path') ?: base_path('../docs/project/email-catalogue.md');
        $all = EmailCatalogue::all();
        $lines = [
            '# Email catalogue',
            '',
            'Generated by `php artisan nawy:emails:catalogue` from `app/Shared/Notifications/Email/Catalogue/*` — edit the code, then regenerate. Texts are the built-in defaults; admins override them per country and language in Admin → Content → Notification templates (preview, test send, reset, version history).',
            '',
            '**Engine:** every event goes through `Emails::send()` / `Emails::alertAdmins()` → one queued `EventEmail` per recipient on the `mail` queue (5 tries, back-off) → channels `mail` (+ `bell` in-app/push, `sms` where listed) → branded EN/AR layout (RTL for Arabic) with a plain-text part, in the recipient\'s language → `email_log` row (queued → sent / failed / suppressed / skipped / bounced / complained). Idempotent per event + entity + recipient. See `docs/deploy/email.md` for providers, DNS and webhooks.',
            '',
            '**Categories:** '.implode(' · ', array_map(fn (EmailCategory $c): string => '`'.$c->value.'` '.($c->isLocked() ? '(always sent)' : ($c->defaultEnabled() ? '(on by default, can be turned off, one-click unsubscribe)' : '(opt-in, one-click unsubscribe)')), EmailCategory::cases())).'. Admin alerts are opted in per alert and only offered for alerts whose permission the admin holds.',
            '',
            '## Counts',
            '',
            '| Recipient | Events | Existing (moved onto the engine) | Added |',
            '|---|---|---|---|',
        ];

        $totals = [0, 0, 0];

        foreach (EmailCatalogue::byActor() as $actor => $events) {
            $existing = count(array_filter($events, fn (array $event): bool => $event['status'] === 'existing'));
            $lines[] = '| '.EmailCatalogue::ACTORS[$actor].' | '.count($events).' | '.$existing.' | '.(count($events) - $existing).' |';
            $totals = [$totals[0] + count($events), $totals[1] + $existing, $totals[2] + count($events) - $existing];
        }

        $lines[] = '| **Total** | **'.$totals[0].'** | **'.$totals[1].'** | **'.$totals[2].'** |';

        foreach (EmailCatalogue::byActor() as $actor => $events) {
            $lines[] = '';
            $lines[] = '## '.EmailCatalogue::ACTORS[$actor];
            $lines[] = '';
            $lines[] = '| Event key | Trigger | Recipient(s) | Category | Channels | Subject EN | Subject AR | Variables | Extras | Status |';
            $lines[] = '|---|---|---|---|---|---|---|---|---|---|';

            foreach ($events as $key => $event) {
                $extras = array_filter([
                    $event['attachment'],
                    $event['permission'] === null ? null : 'permission `'.$event['permission'].'`',
                    $event['sensitive'] ? 'sensitive (not stored, no resend)' : null,
                ]);

                $lines[] = '| `'.$key.'` | '.$this->cell($event['trigger']).' | '.$this->cell($event['recipients']).' | '.$event['category']->value.' | '.implode(', ', $event['channels'])
                    .' | '.$this->cell($event['defaults']['en']['subject']).' | '.$this->cell($event['defaults']['ar']['subject']).' | '.implode(', ', $event['variables'])
                    .' | '.$this->cell(implode('; ', $extras) ?: '—').' | '.$event['status'].' |';
            }
        }

        $lines[] = '';
        $lines[] = '## Scheduled reminders';
        $lines[] = '';
        $lines[] = '`nawy:emails:reminders {kind}` (routes/console.php): `seller-sla` hourly (seller.sla_unconfirmed / seller.sla_not_shipped), `abandoned-carts` hourly (cart.abandoned, opted-in customers only), `document-expiry` daily (document.expiring at 30 and 7 days), `renewal-reminders` daily (membership.renewal_upcoming, subscription.renewal_upcoming), `credit-expiry` daily (wallet.credit_expiring), `review-requests` daily (review.request), `promotion-expiry` daily (travel.promotion_expiring). Ad expiring runs in `nawy:classifieds:expire`, FBN inbound in `nawy:fbn:inbound-reminders`. All respect preferences and are idempotent per entity + window.';
        $lines[] = '';

        file_put_contents($path, implode("\n", $lines));
        $this->info('Wrote '.$path.' ('.count($all).' events).');

        return self::SUCCESS;
    }

    private function cell(string $text): string
    {
        return str_replace(['|', "\n"], ['\\|', ' '], $text);
    }
}
