<?php

namespace App\Domains\Marketers\Support;

use App\Domains\Countries\Support\CountryContext;
use App\Domains\Marketers\Enums\MarketerJobType;
use App\Domains\Marketers\Enums\MarketerStatus;
use App\Domains\Marketers\Models\CelebrityMonthlyReport;
use App\Domains\Marketers\Models\MarketerProfile;
use App\Domains\Marketers\Notifications\CelebrityMonthlyReportReady;
use App\Models\User;
use App\Shared\Money\MoneyFormatter;
use Barryvdh\DomPDF\Facade\Pdf;
use Carbon\CarbonImmutable;
use Illuminate\Contracts\View\View;
use Illuminate\Database\Connection;
use Illuminate\Support\Facades\DB;
use Throwable;

/**
 * Celebrity monthly report (FR-ANL-2, FR-MKT-18, SRS §11.13 "monthly
 * obligations"). A celebrity is a marketer profile with the influencer job
 * type (SRS §11.1: influencers are the celebrity / creator accounts; there
 * is no separate celebrity flag). For the month (the country's local
 * calendar month) each one gets: orders and units attributed to them,
 * attributed sales, conversions by status, net commission, bonuses and
 * settled influencer fixed fees, referral clicks, top products, campaign
 * invitations / content and the cross-promotion obligation result.
 *
 * Generated on the 1st for the previous month (job), regenerated by an admin
 * on request (the row is replaced); the marketer is emailed once, in their
 * language, with the PDF attached.
 */
class CelebrityReports
{
    public function __construct(private CountryContext $countryContext, private MoneyFormatter $formatter) {}

    /**
     * Previous local month of the current country (Y-m).
     */
    public function previousPeriod(): string
    {
        return CarbonImmutable::now($this->countryContext->current()->timezone)->startOfMonth()->subMonth()->format('Y-m');
    }

    /**
     * Generate the month for every influencer of the current country.
     *
     * @return int reports written
     */
    public function generateAll(string $period, bool $email = true, ?int $userId = null): int
    {
        $written = 0;

        foreach ($this->celebrities() as $marketer) {
            $report = $this->generate($marketer, $period, $userId);

            if ($email) {
                $this->email($report);
            }

            $written++;
        }

        return $written;
    }

    /**
     * Influencer profiles that are active or suspended (a suspended one may still have had sales that month).
     *
     * @return iterable<int, MarketerProfile>
     */
    public function celebrities(): iterable
    {
        return MarketerProfile::query()->whereIn('global_status', [MarketerStatus::Active, MarketerStatus::Suspended])->orderBy('id')->get()
            ->filter(fn (MarketerProfile $marketer): bool => $marketer->hasJobType(MarketerJobType::Influencer))->values();
    }

    public function generate(MarketerProfile $marketer, string $period, ?int $userId = null): CelebrityMonthlyReport
    {
        $country = $this->countryContext->current();
        $start = CarbonImmutable::createFromFormat('Y-m-d H:i:s', $period.'-01 00:00:00', $country->timezone);
        [$from, $to] = [$start->utc(), $start->addMonth()->utc()];
        $currency = $country->currency;

        $conversions = $this->db()->table('marketer_conversions')->where('marketer_profile_id', $marketer->id)
            ->where('created_at', '>=', $from)->where('created_at', '<', $to)->where('currency', $currency);
        $kept = (clone $conversions)->where('status', '!=', 'reversed');
        $totals = (clone $kept)->selectRaw('count(*) as conversions, count(distinct order_id) as orders, coalesce(sum(basis), 0) as sales, coalesce(sum(net), 0) as net, coalesce(sum(bonus), 0) as bonus')->first();
        $byStatus = (clone $conversions)->selectRaw('status, count(*) as total')->groupBy('status')->pluck('total', 'status')->map(fn ($total): int => (int) $total)->all();
        $reversed = (string) ((clone $conversions)->where('status', 'reversed')->sum('net') ?: '0');

        $topProducts = $this->db()->table('marketer_conversions')
            ->join('order_items', 'order_items.id', '=', 'marketer_conversions.source_id')
            ->where('marketer_conversions.source_type', 'order_item')->where('marketer_conversions.marketer_profile_id', $marketer->id)
            ->where('marketer_conversions.status', '!=', 'reversed')->where('marketer_conversions.currency', $currency)
            ->where('marketer_conversions.created_at', '>=', $from)->where('marketer_conversions.created_at', '<', $to)
            ->selectRaw('order_items.listing_id, max(order_items.title) as title, sum(order_items.quantity) as units, sum(marketer_conversions.basis) as sales')
            ->groupBy('order_items.listing_id')->orderByDesc('sales')->limit(5)->get()
            ->map(fn (object $row): array => ['listing_id' => (int) $row->listing_id, 'title' => (string) $row->title, 'units' => (int) $row->units, 'sales' => (string) $row->sales])->all();
        $units = (int) array_sum(array_column($this->db()->table('marketer_conversions')
            ->join('order_items', 'order_items.id', '=', 'marketer_conversions.source_id')
            ->where('marketer_conversions.source_type', 'order_item')->where('marketer_conversions.marketer_profile_id', $marketer->id)
            ->where('marketer_conversions.status', '!=', 'reversed')->where('marketer_conversions.currency', $currency)
            ->where('marketer_conversions.created_at', '>=', $from)->where('marketer_conversions.created_at', '<', $to)
            ->selectRaw('sum(order_items.quantity) as units')->get()->all(), 'units'));

        $invitations = $this->db()->table('campaign_invitations')->where('marketer_profile_id', $marketer->id);
        $fixedFees = (string) ((clone $invitations)->where('influencer_fixed_status', 'settled')->where('updated_at', '>=', $from)->where('updated_at', '<', $to)->sum('influencer_fixed') ?: '0');
        $campaigns = [
            'invitations' => (clone $invitations)->where('created_at', '>=', $from)->where('created_at', '<', $to)->count(),
            'accepted' => (clone $invitations)->where('accepted_at', '>=', $from)->where('accepted_at', '<', $to)->count(),
            'active' => (clone $invitations)->where('status', 'accepted')->where('created_at', '<', $to)
                ->where(fn ($query) => $query->whereNull('closed_at')->orWhere('closed_at', '>=', $from))->count(),
            'content_approved' => $this->db()->table('content_submissions')->where('marketer_profile_id', $marketer->id)->where('status', 'approved')
                ->where('reviewed_at', '>=', $from)->where('reviewed_at', '<', $to)->count(),
        ];
        $crossPromotion = $this->db()->table('cross_promo_participations')->join('cross_promo_policies', 'cross_promo_policies.id', '=', 'cross_promo_participations.policy_id')
            ->where('cross_promo_participations.marketer_profile_id', $marketer->id)->where('cross_promo_participations.period', $period)
            ->orderBy('cross_promo_policies.id')
            ->get(['cross_promo_policies.name', 'cross_promo_participations.required', 'cross_promo_participations.completed', 'cross_promo_participations.status'])
            ->map(fn (object $row): array => ['policy' => (string) $row->name, 'required' => (int) $row->required, 'completed' => (int) $row->completed, 'status' => (string) $row->status])->all();
        $clicks = $this->db()->table('referral_clicks')->where('marketer_profile_id', $marketer->id)->where('clicked_at', '>=', $from)->where('clicked_at', '<', $to)->count();

        $net = (string) $totals->net;
        $bonus = (string) $totals->bonus;

        return CelebrityMonthlyReport::query()->updateOrCreate(
            ['marketer_profile_id' => $marketer->id, 'period' => $period],
            [
                'currency' => $currency,
                'orders_count' => (int) $totals->orders,
                'units_sold' => $units,
                'attributed_sales' => (string) $totals->sales,
                'conversions_count' => (int) $totals->conversions,
                'commission_net' => $net,
                'bonus_total' => $bonus,
                'fixed_fees' => $fixedFees,
                'total_earnings' => bcadd(bcadd($net, $bonus, 4), $fixedFees, 4),
                'referral_clicks' => $clicks,
                'metrics' => [
                    'conversions_by_status' => $byStatus,
                    'top_products' => $topProducts,
                    'campaigns' => $campaigns,
                    'cross_promotion' => $crossPromotion,
                    'reversed_commission' => $reversed,
                ],
                'generated_by_user_id' => $userId,
                'generated_at' => now(),
            ],
        );
    }

    /**
     * Mail the report once to the marketer's account, with the PDF.
     */
    public function email(CelebrityMonthlyReport $report): bool
    {
        if ($report->emailed_at !== null) {
            return false;
        }

        $user = User::query()->find($report->marketer?->user_id);

        if ($user === null || blank($user->email)) {
            return false;
        }

        try {
            $user->notify(new CelebrityMonthlyReportReady($report, $this->countryContext->current()->code));
        } catch (Throwable $exception) {
            report($exception);

            return false;
        }

        $report->forceFill(['emailed_at' => now()])->save();

        return true;
    }

    public function view(CelebrityMonthlyReport $report, bool $forPdf = false): View
    {
        return view('reports.celebrity-monthly', [
            'report' => $report,
            'marketer' => $report->marketer,
            'country' => $this->countryContext->current(),
            'money' => fn (string $amount): string => $this->formatter->format($amount, $report->currency),
            'forPdf' => $forPdf,
        ]);
    }

    public function pdf(CelebrityMonthlyReport $report): string
    {
        return Pdf::loadHTML($this->view($report, true)->render())->setPaper('a4')->output();
    }

    private function db(): Connection
    {
        return DB::connection($this->countryContext->connectionName());
    }
}
