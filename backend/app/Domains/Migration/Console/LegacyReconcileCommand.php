<?php

namespace App\Domains\Migration\Console;

use App\Domains\Migration\Support\LegacySource;
use App\Domains\Migration\Support\MigrationContext;
use App\Domains\Migration\Support\Reconciler;
use Illuminate\Console\Attributes\Description;
use Illuminate\Console\Attributes\Signature;
use Illuminate\Console\Command;
use Illuminate\Support\Facades\DB;
use Illuminate\Support\Facades\File;

#[Signature('legacy:reconcile {--report=docs/project/migration/reconciliation-report.md : Where to write the report, relative to the repository root}')]
#[Description('WP11: reconcile the legacy snapshot with the migrated data (row counts, money, ledger, wallets, statuses, identity, signatures, files) and write the report')]
class LegacyReconcileCommand extends Command
{
    public function handle(LegacySource $source): int
    {
        $reconciler = new Reconciler($source);
        $counts = $reconciler->rowCounts();
        $countries = $reconciler->countryCounts();
        $orphans = $reconciler->orphans();
        $money = $reconciler->money();
        $ledger = $reconciler->ledger();
        $statuses = $reconciler->statuses();
        $identity = $reconciler->identity();
        $signatures = $reconciler->signatures();
        $files = $reconciler->files();
        $quarantine = $reconciler->quarantine();

        $report = $this->render($counts, $countries, $orphans, $money, $ledger, $statuses, $identity, $signatures, $files, $quarantine, $reconciler->differences);
        $path = $this->option('report');
        $full = str_starts_with((string) $path, '/') ? (string) $path : dirname(base_path()).'/'.$path;
        File::ensureDirectoryExists(dirname($full));
        File::put($full, $report);

        $this->components->info("Report written to {$path}");
        $this->table(['check', 'result'], [
            ['legacy tables', count($counts)],
            ['legacy rows', array_sum(array_column($counts, 'source'))],
            ['migrated / archived', array_sum(array_column($counts, 'migrated'))],
            ['folded / dropped by rule', array_sum(array_column($counts, 'explained'))],
            ['quarantined', array_sum(array_column($counts, 'quarantined'))],
            ['ledger transactions (unbalanced)', $ledger['transactions'].' ('.$ledger['unbalanced'].')'],
            ['wallets (mismatches)', $ledger['wallets'].' ('.$ledger['wallet_mismatches'].')'],
            ['signatures verified', $signatures['verified'].' / '.$signatures['signatures']],
            ['files verified', $files['present'].' / '.$files['referenced']],
            ['differences', count($reconciler->differences)],
        ]);

        foreach ($reconciler->differences as $difference) {
            $this->components->warn(Reconciler::mask($difference));
        }

        return $reconciler->differences === [] ? self::SUCCESS : self::FAILURE;
    }

    /**
     * @param  array<int, array<string, mixed>>  $counts
     * @param  array<string, array<string, int>>  $countries
     * @param  array<string, int>  $orphans
     * @param  array<int, array<string, mixed>>  $money
     * @param  array<string, int>  $ledger
     * @param  array<string, array<string, array{legacy: int, target: int}>>  $statuses
     * @param  array<string, int>  $identity
     * @param  array<string, int>  $signatures
     * @param  array<string, int>  $files
     * @param  array<int, array<string, mixed>>  $quarantine
     * @param  array<int, string>  $differences
     */
    private function render(array $counts, array $countries, array $orphans, array $money, array $ledger, array $statuses, array $identity, array $signatures, array $files, array $quarantine, array $differences): string
    {
        $lastRun = DB::table('migration_runs')->latest('id')->first();
        $codes = [MigrationContext::CENTRAL, ...MigrationContext::allCountries()];
        $lines = [
            '# Legacy migration — reconciliation report',
            '',
            'Generated by `php artisan legacy:reconcile` on '.now()->toDateTimeString().' (server time). Source: the `legacy` snapshot connection (`'.config('database.connections.legacy.database').'`, read only). Last migration run: '.($lastRun ? "`{$lastRun->run_id}` ({$lastRun->finished_at})" : 'none').'. PII is masked.',
            '',
            '## Result',
            '',
            $differences === [] ? '**Clean:** every legacy row is migrated, archived, folded/dropped by rule or quarantined with a reason; every money, ledger, wallet, status, signature and file check passes.' : '**'.count($differences).' unexplained difference(s):**',
            '',
        ];

        foreach ($differences as $difference) {
            $lines[] = '- '.Reconciler::mask($difference);
        }

        $lines[] = '';
        $lines[] = '| | Rows |';
        $lines[] = '|---|---:|';
        $lines[] = '| Legacy rows (tables present in the snapshot: '.count($counts).') | '.array_sum(array_column($counts, 'source')).' |';
        $lines[] = '| Migrated or archived | '.array_sum(array_column($counts, 'migrated')).' |';
        $lines[] = '| Folded into another table / dropped by rule (R8) | '.array_sum(array_column($counts, 'explained')).' |';
        $lines[] = '| Quarantined (reasons below) | '.array_sum(array_column($counts, 'quarantined')).' |';
        $lines[] = '';

        $lines[] = '## Rows written per country';
        $lines[] = '';
        $lines[] = '| Target table | '.implode(' | ', $codes).' |';
        $lines[] = '|---|'.str_repeat('---:|', count($codes));

        foreach ($countries as $table => $perDb) {
            $lines[] = "| {$table} | ".implode(' | ', array_map(fn (string $code): string => (string) ($perDb[$code] ?? 0), $codes)).' |';
        }

        $lines[] = '';
        $lines[] = '## Quarantine';
        $lines[] = '';

        if ($quarantine === []) {
            $lines[] = 'Nothing quarantined.';
        } else {
            $lines[] = '| Table | Reason | Rows | Example |';
            $lines[] = '|---|---|---:|---|';

            foreach ($quarantine as $row) {
                $lines[] = "| {$row['table']} | {$row['reason']} | {$row['count']} | ".str_replace('|', '/', $row['detail']).' |';
            }
        }

        $lines[] = '';
        $lines[] = '## Money (per currency, exact)';
        $lines[] = '';
        $lines[] = '| Check | Currency | Legacy | New | Equal |';
        $lines[] = '|---|---|---:|---:|---|';

        foreach ($money as $row) {
            $lines[] = "| {$row['check']} | {$row['currency']} | {$row['legacy']} | {$row['target']} | ".($row['equal'] ? 'yes' : '**no**').' |';
        }

        $lines[] = '';
        $lines[] = "Ledger: {$ledger['transactions']} migrated transaction(s), {$ledger['unbalanced']} unbalanced. Wallets: {$ledger['wallets']} migrated account(s), {$ledger['wallet_mismatches']} not reproducing the legacy balance (account balance and Σ entries both checked).";
        $lines[] = '';
        $lines[] = '## Statuses (migrated rows)';
        $lines[] = '';
        $lines[] = '| Table | Status | Legacy | New |';
        $lines[] = '|---|---|---:|---:|';

        foreach ($statuses as $table => $perStatus) {
            foreach ($perStatus as $status => $pair) {
                $lines[] = "| {$table} | {$status} | {$pair['legacy']} | {$pair['target']} |";
            }
        }

        $lines[] = '';
        $lines[] = 'Order roll-up: every migrated order status equals `OrderStatusRollup::derive()` of its sub-orders (differences above if not).';
        $lines[] = '';
        $lines[] = '## Identity';
        $lines[] = '';
        $lines[] = '| | Count |';
        $lines[] = '|---|---:|';

        foreach ($identity as $label => $value) {
            $lines[] = "| {$label} | {$value} |";
        }

        $lines[] = '';
        $lines[] = '## Integrity';
        $lines[] = '';
        $lines[] = "- Contract signatures: {$signatures['verified']} of {$signatures['signatures']} migrated frozen copies verify (legacy SHA-256 re-checked before the move).";
        $lines[] = "- Files: {$files['present']} of {$files['referenced']} referenced legacy files are present in new storage with the same SHA-256 (missing ones are quarantined `file_missing`).";
        $lines[] = '- Orphans: '.($orphans === [] ? 'none — every id-map entry has its target row and the checked foreign keys resolve.' : implode(', ', array_map(fn (string $key, int $count): string => "{$key}: {$count}", array_keys($orphans), $orphans))).'';
        $lines[] = '';
        $lines[] = '## Row counts per legacy table';
        $lines[] = '';
        $lines[] = '"Migrated" counts distinct legacy rows with at least one target (a replicated R4 row has one per country, see above); archived rows are in `legacy_records`.';
        $lines[] = '';
        $lines[] = '| Table | Rule | Disposition | Source | Migrated / archived | Quarantined | Folded / dropped | Difference |';
        $lines[] = '|---|---|---|---:|---:|---:|---:|---:|';

        foreach ($counts as $row) {
            if ($row['source'] === 0) {
                continue;
            }

            $lines[] = "| {$row['table']} | {$row['rule']} | {$row['disposition']} | {$row['source']} | {$row['migrated']} | {$row['quarantined']} | {$row['explained']} | ".($row['difference'] === 0 ? '0' : "**{$row['difference']}**").' |';
        }

        $empty = array_column(array_filter($counts, fn (array $row): bool => $row['source'] === 0), 'table');
        $lines[] = '';
        $lines[] = count($empty).' further legacy tables are empty in the snapshot (rules still apply on a fresh snapshot): '.implode(', ', $empty).'.';
        $lines[] = '';

        return implode("\n", $lines);
    }
}
