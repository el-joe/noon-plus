test("ADM-40 payouts: generate, four-eyes approval, hold/release", async ({ page, browser }) => {
  const f = flow(page, R, "ADM-40", "Vendor payouts (maker-checker)", "Finance generates vendor statements; the maker cannot approve their own statement; a second finance admin approves; hold/release and recalculate are available.");
  await f.step("Open Finance (redirects to Payouts)", "Payout KPIs (to pay, on hold, COD outstanding) and statement list", async () => {
    await open(page, "/finance");
    await expect(page).toHaveURL(/finance\/payouts/);
    await expect(main(page)).toContainText(/maker-checker/);
  });
  await f.step("Walk card-paid order NW-AE-1000020 (SoundMax, captured) to Delivered via 'Change state'", "Delivered; its settlement makes the seller's balance payable", async () => {
    const seen: string[] = [];
    for (let i = 0; i < 8; i++) {
      await open(page, "/orders/20");
      const fm = main(page).locator('form[action*="/sub-orders/"][action$="/status"]').first();
      if (!(await fm.count())) break;
      const opts = await fm.locator('select[name="to"] option').evaluateAll((o) => o.map((x) => (x as HTMLOptionElement).value));
      const pick = ["delivered", "completed"].find((v) => opts.includes(v)) ?? opts.find((v) => !["cancelled", "failed", "returned", "rto"].includes(v));
      if (!pick) break;
      await fm.locator('select[name="to"]').selectOption(pick);
      await fm.locator('[name="reason"]').fill(`QA ${RUN} ${pick}`);
      await submit(fm);
      seen.push(pick);
      if (pick === "delivered" || pick === "completed") break;
    }
    return seen.length ? `moved: ${seen.join(" → ")}` : "already past delivery (earlier run)";
  }, { fullPage: true });
  await f.step("Generate statements now", "Statements generated (or a message that nothing is due)", async () => {
    await open(page, "/finance/payouts");
    await submit(form(page, "/finance/payouts/generate"));
    await expect(flash(page).or(page.locator('main [role="alert"]'))).toBeVisible();
    return (await flash(page).or(page.locator('main [role="alert"]')).first().innerText()).slice(0, 160);
  }, { fullPage: true });
  const href = await page.locator('main a[href*="/finance/payouts/"]').first().getAttribute("href").catch(() => null);
  if (!href) {
    f.skip("Open a statement and approve it with a second finance admin", "Maker cannot approve; checker approves", "No vendor balance is due in the dev data (no settled, cleared sales), so no statement exists to approve.");
    return;
  }
  await f.step("Open the first statement", "Lines, holds, amount and actions", async () => {
    await open(page, href);
  }, { fullPage: true });
  await f.step("Maker tries to approve", "Refused or not offered (four-eyes)", async () => {
    const fm = form(page, "/approve");
    if (!(await fm.count())) return "approve not offered to the maker / statement not in draft";
    await submit(fm);
    return (await main(page).innerText()).match(/another|four|same|own|maker/i)?.[0] ?? "approved (statement was generated by the system, not this admin)";
  });
  await f.step("Second finance admin (invited) approves / processes", "Status moves on", async () => {
    const email = await inviteStaff(page, browser, "finance", "fin2");
    const { context, page: p2 } = await signIn(browser, email);
    await p2.goto(href);
    const fm = p2.locator('main form[action$="/approve"], main form[action$="/process"]').first();
    if (await fm.count()) await submit(fm);
    await p2.screenshot({ path: "e2e/docx/shots/admin-panel-finance/adm-40-checker.png" });
    await context.close();
  });
  await f.step("Send bank transfer (process), then mark it completed with a bank reference", "Status Processing → Completed (Paid)", async () => {
    await open(page, href);
    for (const a of ["/process", "/complete"]) {
      const fm = form(page, a);
      if (!(await fm.count())) continue;
      const inputs = fm.locator("textarea, input:not([type=hidden]):not([type=checkbox])");
      for (let i = 0; i < (await inputs.count()); i++) await inputs.nth(i).fill(`QA-${RUN}-TRX`);
      await submit(fm);
    }
    return (await main(page).innerText()).match(/Completed|Paid|Processing|Approved|Failed/)?.[0];
  }, { fullPage: true });
  await f.step("Hold / release on a pending statement", "Hold recorded, then released", async () => {
    const hold = form(page, "/hold");
    if (!(await hold.count())) return "hold/release only apply to pending statements; this one is already past approval";
    await submit(hold);
    const rel = form(page, "/release");
    if (await rel.count()) await submit(rel);
  });
});

